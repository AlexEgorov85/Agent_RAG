def _normalize(text: str) -> str:
    folded = unicodedata.normalize("NFKC", text).lower().replace("ё", "е")
    folded = _PUNCTUATION.sub(" ", folded)
    return _SPACES.sub(" ", folded).strip()


def _is_capability_question(normalized: str) -> bool:
    # Предметная лексика важнее местоимения/глагола: «ты умеешь считать
    # выручку?» — вопрос по корпусу, а не о возможностях ассистента.
    if any(marker in normalized for marker in _DOMAIN_MARKERS):
        return False
    words = set(normalized.split())
    if "умеешь" in normalized:
        return True
    if normalized in {"помощь", "help"} or normalized in _CAPABILITY_SHORT_FORMS:
        return True
    if any(phrase in normalized for phrase in _CAPABILITIES):
        return True
    if not words & _SECOND_PERSON:
        return False
    return any(marker in normalized for marker in _CAPABILITY_VERBS)


def smalltalk_reply(query: str) -> str | None:
    """Возвращает готовый ответ на служебную реплику или ``None``.

    ``None`` означает «это не small talk»: запрос должен идти обычным путём
    через роутер, retrieval и генератор по источникам.
    """
    if not isinstance(query, str):
        return None
    normalized = _normalize(query)
    if not normalized or len(normalized) > MAX_SMALLTALK_CHARS:
        return None
    if any(char.isdigit() for char in normalized):
        return None

    if normalized in _GREETINGS:
        return GREETING_REPLY
    if normalized in _HOW_ARE_YOU:
        return HOW_ARE_YOU_REPLY
    if normalized in _THANKS:
        return THANKS_REPLY
    if normalized in _BYE:
        return BYE_REPLY
    if _is_capability_question(normalized):
        return CAPABILITIES_REPLY
    return None
