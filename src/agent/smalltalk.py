"""Короткие ответы на служебные реплики, не относящиеся к корпусу.

Retrieval по приветствию ничего не находит, и правило «отвечай только по
источникам» превращало «Привет!» в ``abstain`` с предупреждением
``no_evidence``. Это честно, но выглядит как отказ отвечать.

Детектор намеренно узкий: он срабатывает, только когда всё сообщение целиком
является приветствием, благодарностью, прощанием или вопросом о возможностях.
Поэтому «Привет! Какая чистая прибыль за 2023 год?» уходит в обычный
RAG-маршрут, а гарантия «ответ только по подтверждённым источникам» не
затрагивается: это реплики вне корпуса, а не ответы по документам.
"""

